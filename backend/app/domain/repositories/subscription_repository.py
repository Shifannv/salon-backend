"""Subscription repository ports — provider-agnostic."""

from typing import Any, Protocol


class SubscriptionPlanRepository(Protocol):
    async def list_plans(self, *, include_inactive: bool = False) -> list[dict[str, Any]]: ...
    async def get_plan(self, plan_id: str) -> dict[str, Any]: ...
    async def create_plan(self, values: dict[str, Any]) -> dict[str, Any]: ...
    async def update_plan(self, plan_id: str, values: dict[str, Any]) -> dict[str, Any]: ...
    async def deactivate_plan(self, plan_id: str) -> dict[str, Any]: ...


class SubscriptionRepository(Protocol):
    async def get_salon_subscription(self, salon_id: str) -> dict[str, Any] | None: ...
    async def create_subscription(self, values: dict[str, Any]) -> dict[str, Any]: ...
    async def update_subscription_status(
        self, subscription_id: str, status: str, **kwargs: Any
    ) -> dict[str, Any]: ...
    async def get_active_promotion_weight(self, salon_id: str) -> int:
        """Return the ranking_weight of the salon's active promoted subscription, or 0."""
        ...


class SubscriptionEventRepository(Protocol):
    async def record_event(self, values: dict[str, Any]) -> dict[str, Any]: ...
    async def list_events(
        self, *, subscription_id: str | None = None, limit: int = 50, offset: int = 0
    ) -> list[dict[str, Any]]: ...
    async def mark_event_processed(self, event_id: str) -> None: ...
    async def mark_event_failed(self, event_id: str, error: str) -> None: ...


class SubscriptionProviderAdapter(Protocol):
    """Future provider adapter interface.

    Implementations translate external provider events into internal domain
    commands.  No SDK-specific types cross this boundary.
    """

    @property
    def provider_name(self) -> str: ...

    async def verify_webhook_signature(self, payload: bytes, headers: dict[str, str]) -> bool:
        """Verify that the payload was signed by the provider."""
        ...

    async def parse_event(self, payload: dict[str, Any]) -> dict[str, Any]:
        """Parse a raw webhook payload into an internal event dict."""
        ...
